// ── Types ─────────────────────────────────────────────────────────────────────

// Relationship mirrors the relationships table row.
type Relationship struct {
	ID               string
	FromEntityID     string
	ToEntityID       string
	RelationshipType string // e.g. supplies_to, competes_with, sector_member …
	Strength         float64
	Description      string
	AutoGenerated    bool
	Confidence       *float64
	ValidFrom        *time.Time
	ValidUntil       *time.Time
	CreatedAt        time.Time
}

// EntityMention records a link between an entity and a news item.
type EntityMention struct {
	ID             string
	EntityID       string
	NewsItemID     string
	RelevanceScore *float64
	CreatedAt      time.Time
}

// EntityRelationship joins a Relationship with the details of the related entity
// — used when building context blocks.
type EntityRelationship struct {
	Relationship
	RelatedEntity Entity // the entity on the other end of the edge
	Direction     string // "outbound" or "inbound"
}

// ── Relationship CRUD ─────────────────────────────────────────────────────────

// UpsertRelationship inserts or refreshes a relationship.
// Conflict key: (from_entity_id, to_entity_id, relationship_type).
func UpsertRelationship(ctx context.Context, r Relationship) (string, error) {
	var id string
	err := GetDB().QueryRow(ctx, `
		INSERT INTO relationships (
			from_entity_id, to_entity_id, relationship_type,
			strength, description, auto_generated, confidence, valid_from, valid_until
		) VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)
		ON CONFLICT (from_entity_id, to_entity_id, relationship_type) DO UPDATE
		  SET strength       = EXCLUDED.strength,
		      description    = EXCLUDED.description,
		      auto_generated = EXCLUDED.auto_generated,
		      confidence     = EXCLUDED.confidence,
		      valid_from     = EXCLUDED.valid_from,
		      valid_until    = EXCLUDED.valid_until
		RETURNING id`,
		r.FromEntityID, r.ToEntityID, r.RelationshipType,
		r.Strength,
		nullableString(r.Description),
		r.AutoGenerated,
		r.Confidence,
		r.ValidFrom,
		r.ValidUntil,
	).Scan(&id)
	if err != nil {
		return "", fmt.Errorf("upsert relationship %s→%s (%s): %w",
			r.FromEntityID, r.ToEntityID, r.RelationshipType, err)
	}
	return id, nil
}

// GetRelationshipsForEntity returns all 1-hop relationships where the given
// entity ID appears on either side of the edge, enriched with the related entity.
func GetRelationshipsForEntity(ctx context.Context, entityID string) ([]EntityRelationship, error) {
	rows, err := GetDB().Query(ctx, `
		SELECT
			r.id, r.from_entity_id, r.to_entity_id, r.relationship_type,
			r.strength, COALESCE(r.description,''), r.auto_generated,
			r.confidence, r.valid_from, r.valid_until, r.created_at,
			-- related entity (outbound: to_entity; inbound: from_entity)
			CASE WHEN r.from_entity_id = $1 THEN e2.id   ELSE e1.id   END,
			CASE WHEN r.from_entity_id = $1 THEN e2.entity_type ELSE e1.entity_type END,
			CASE WHEN r.from_entity_id = $1 THEN e2.name  ELSE e1.name  END,
			CASE WHEN r.from_entity_id = $1 THEN COALESCE(e2.ticker,'') ELSE COALESCE(e1.ticker,'') END,
			CASE WHEN r.from_entity_id = $1 THEN COALESCE(e2.description,'') ELSE COALESCE(e1.description,'') END,
			CASE WHEN r.from_entity_id = $1 THEN COALESCE(e2.sector,'') ELSE COALESCE(e1.sector,'') END,
			CASE WHEN r.from_entity_id = $1 THEN COALESCE(e2.country,'') ELSE COALESCE(e1.country,'') END,
			CASE WHEN r.from_entity_id = $1 THEN e2.created_at ELSE e1.created_at END,
			CASE WHEN r.from_entity_id = $1 THEN e2.updated_at ELSE e1.updated_at END,
			CASE WHEN r.from_entity_id = $1 THEN 'outbound' ELSE 'inbound' END
		FROM relationships r
		JOIN entities e1 ON e1.id = r.from_entity_id
		JOIN entities e2 ON e2.id = r.to_entity_id
		WHERE r.from_entity_id = $1 OR r.to_entity_id = $1
		ORDER BY r.strength DESC, r.relationship_type`,
		entityID,
	)
	if err != nil {
		return nil, fmt.Errorf("get 1-hop relationships for %q: %w", entityID, err)
	}
	defer rows.Close()
	return collectEntityRelationships(rows)
}

// Get2HopRelationships returns 1-hop + 2-hop relationships for the given entity.
// It first fetches 1-hop neighbours, then fetches their outbound relationships.
// Results are deduplicated by relationship ID.
func Get2HopRelationships(ctx context.Context, entityID string) ([]EntityRelationship, error) {
	hop1, err := GetRelationshipsForEntity(ctx, entityID)
	if err != nil {
		return nil, err
	}

	seen := make(map[string]bool)
	all := make([]EntityRelationship, 0, len(hop1)*4)
	for _, r := range hop1 {
		if !seen[r.ID] {
			seen[r.ID] = true
			all = append(all, r)
		}
	}

	// Collect unique neighbour IDs.
	neighbourIDs := make(map[string]bool)
	for _, r := range hop1 {
		neighbourIDs[r.RelatedEntity.ID] = true
	}
	for nid := range neighbourIDs {
		hop2, err := GetRelationshipsForEntity(ctx, nid)
		if err != nil {
			continue // non-fatal; best-effort 2-hop
		}
		for _, r := range hop2 {
			if !seen[r.ID] {
				seen[r.ID] = true
				all = append(all, r)
			}
		}
	}
	return all, nil
}

// GetPendingAutoRelationships returns auto-generated relationships with no
// manual review yet (confidence is set by the extractor, awaiting accept/reject).
func GetPendingAutoRelationships(ctx context.Context) ([]EntityRelationship, error) {
	rows, err := GetDB().Query(ctx, `
		SELECT
			r.id, r.from_entity_id, r.to_entity_id, r.relationship_type,
			r.strength, COALESCE(r.description,''), r.auto_generated,
			r.confidence, r.valid_from, r.valid_until, r.created_at,
			e2.id, e2.entity_type, e2.name, COALESCE(e2.ticker,''),
			COALESCE(e2.description,''), COALESCE(e2.sector,''), COALESCE(e2.country,''),
			e2.created_at, e2.updated_at,
			'outbound'
		FROM relationships r
		JOIN entities e1 ON e1.id = r.from_entity_id
		JOIN entities e2 ON e2.id = r.to_entity_id
		WHERE r.auto_generated = TRUE
		ORDER BY r.created_at DESC`,
	)
	if err != nil {
		return nil, fmt.Errorf("get pending auto relationships: %w", err)
	}
	defer rows.Close()
	return collectEntityRelationships(rows)
}

// DeleteRelationship removes a relationship by ID.
func DeleteRelationship(ctx context.Context, id string) error {
	_, err := GetDB().Exec(ctx, `DELETE FROM relationships WHERE id = $1`, id)
	return err
}

// ── Entity Mention CRUD ───────────────────────────────────────────────────────

// UpsertEntityMention records that entity appeared in a news item.
// Conflict on (entity_id, news_item_id) does nothing — idempotent.
func UpsertEntityMention(ctx context.Context, entityID, newsItemID string, relevance *float64) error {
	_, err := GetDB().Exec(ctx, `
		INSERT INTO entity_mentions (entity_id, news_item_id, relevance_score)
		VALUES ($1, $2, $3)
		ON CONFLICT (entity_id, news_item_id) DO NOTHING`,
		entityID, newsItemID, relevance,
	)
	if err != nil {
		return fmt.Errorf("upsert entity mention: %w", err)
	}
	return nil
}

// GetNewsIDsForEntity returns news_item UUIDs for an entity, newest first.
func GetNewsIDsForEntity(ctx context.Context, entityID string, limit int) ([]string, error) {
	rows, err := GetDB().Query(ctx, `
		SELECT news_item_id FROM entity_mentions
		WHERE entity_id = $1
		ORDER BY created_at DESC LIMIT $2`, entityID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var ids []string
	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, err
		}
		ids = append(ids, id)
	}
	return ids, rows.Err()
}

// ── Helpers ───────────────────────────────────────────────────────────────────

func collectEntityRelationships(rows pgx.Rows) ([]EntityRelationship, error) {
	var out []EntityRelationship
	for rows.Next() {
		var er EntityRelationship
		var rel = &er.Relationship
		var ent = &er.RelatedEntity
		if err := rows.Scan(
			&rel.ID, &rel.FromEntityID, &rel.ToEntityID, &rel.RelationshipType,
			&rel.Strength, &rel.Description, &rel.AutoGenerated,
			&rel.Confidence, &rel.ValidFrom, &rel.ValidUntil, &rel.CreatedAt,
			&ent.ID, &ent.EntityType, &ent.Name, &ent.Ticker,
			&ent.Description, &ent.Sector, &ent.Country,
			&ent.CreatedAt, &ent.UpdatedAt,
			&er.Direction,
		); err != nil {
			return nil, fmt.Errorf("scan entity relationship: %w", err)
		}
		out = append(out, er)
	}
	return out, rows.Err()
}
