package knowledge

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"runtime"

	"github.com/romeo-folie/trade-engine/internal/store"
)

// seedFile returns the absolute path to the bundled knowledge_graph.json.
// It resolves relative to the Go source tree so the CLI binary can locate the
// file regardless of the working directory at runtime.
//
// For production binaries the file is embedded via go:embed; for development
// builds we walk up from the caller's source file.
func seedFilePath() string {
	_, callerFile, _, _ := runtime.Caller(0)
	// callerFile = .../internal/knowledge/seed.go
	// project root = two directories up from internal/knowledge/
	root := filepath.Join(filepath.Dir(callerFile), "..", "..", "data", "seed", "knowledge_graph.json")
	abs, _ := filepath.Abs(root)
	return abs
}

// seedDoc is the in-memory representation of knowledge_graph.json.
type seedDoc struct {
	Entities      []seedEntity       `json:"entities"`
	Relationships []seedRelationship `json:"relationships"`
}

type seedEntity struct {
	Ref         string `json:"ref"`
	EntityType  string `json:"entity_type"`
	Name        string `json:"name"`
	Ticker      string `json:"ticker"`
	Description string `json:"description"`
	Sector      string `json:"sector"`
	Country     string `json:"country"`
}

type seedRelationship struct {
	FromRef     string  `json:"from_ref"`
	ToRef       string  `json:"to_ref"`
	Type        string  `json:"type"`
	Strength    float64 `json:"strength"`
	Description string  `json:"description"`
}

// SeedStats reports how many rows were processed.
type SeedStats struct {
	EntitiesUpserted      int
	RelationshipsUpserted int
}

// Seed loads knowledge_graph.json and idempotently upserts all entities and
// relationships.  It returns a summary of what was processed.
func Seed(ctx context.Context) (SeedStats, error) {
	return SeedFromFile(ctx, seedFilePath())
}

// SeedFromFile is like Seed but accepts an explicit path — useful for testing.
func SeedFromFile(ctx context.Context, path string) (SeedStats, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return SeedStats{}, fmt.Errorf("read seed file %s: %w", path, err)
	}
	var doc seedDoc
	if err := json.Unmarshal(raw, &doc); err != nil {
		return SeedStats{}, fmt.Errorf("parse seed file: %w", err)
	}

	// Pass 1 — upsert entities, build ref→ID map.
	refToID := make(map[string]string, len(doc.Entities))
	stats := SeedStats{}
	for _, se := range doc.Entities {
		id, err := store.UpsertEntity(ctx, store.Entity{
			EntityType:  se.EntityType,
			Name:        se.Name,
			Ticker:      se.Ticker,
			Description: se.Description,
			Sector:      se.Sector,
			Country:     se.Country,
		})
		if err != nil {
			return stats, fmt.Errorf("seed entity %q: %w", se.Name, err)
		}
		refToID[se.Ref] = id
		stats.EntitiesUpserted++
	}

	// Pass 2 — upsert relationships.
	for _, sr := range doc.Relationships {
		fromID, ok1 := refToID[sr.FromRef]
		toID, ok2 := refToID[sr.ToRef]
		if !ok1 || !ok2 {
			return stats, fmt.Errorf("seed relationship: unknown ref %q→%q (check spelling)", sr.FromRef, sr.ToRef)
		}
		strength := sr.Strength
		if strength == 0 {
			strength = 1.0
		}
		if _, err := store.UpsertRelationship(ctx, store.Relationship{
			FromEntityID:     fromID,
			ToEntityID:       toID,
			RelationshipType: sr.Type,
			Strength:         strength,
			Description:      sr.Description,
			AutoGenerated:    false,
		}); err != nil {
			return stats, fmt.Errorf("seed relationship %s→%s (%s): %w",
				sr.FromRef, sr.ToRef, sr.Type, err)
		}
		stats.RelationshipsUpserted++
	}

	return stats, nil
}
