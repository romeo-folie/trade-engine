// ── Root ─────────────────────────────────────────────────────────────────────

var graphCmd = &cobra.Command{
	Use:   "graph",
	Short: "Manage the entity–relationship knowledge graph",
	Long: `Commands for seeding, browsing, and reviewing the TradeEngine knowledge graph.

The knowledge graph stores entity relationships (supply chain, competition,
sector membership) used to enrich LLM analysis prompts.`,
}

func init() {
	graphCmd.AddCommand(graphSeedCmd)
	graphCmd.AddCommand(graphEntitiesCmd)
	graphCmd.AddCommand(graphRelationshipsCmd)
	graphCmd.AddCommand(graphReviewCmd)
}

// ── te graph seed ─────────────────────────────────────────────────────────────

var graphSeedCmd = &cobra.Command{
	Use:   "seed",
	Short: "Populate the graph from the bundled seed file (idempotent)",
	Long: `Loads data/seed/knowledge_graph.json and upserts all entities and
relationships. Safe to run multiple times — existing rows are updated in place.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		if err := connectDB(); err != nil {
			return err
		}
		defer store.Close()

		fmt.Println("Seeding knowledge graph…")
		stats, err := knowledge.Seed(context.Background())
		if err != nil {
			return fmt.Errorf("seed: %w", err)
		}
		fmt.Printf("Done. %d entities upserted, %d relationships upserted.\n",
			stats.EntitiesUpserted, stats.RelationshipsUpserted)
		return nil
	},
}

// ── te graph entities ─────────────────────────────────────────────────────────

var graphEntitiesTypeFilter string

var graphEntitiesCmd = &cobra.Command{
	Use:   "entities",
	Short: "List all entities in the graph",
	RunE: func(cmd *cobra.Command, args []string) error {
		if err := connectDB(); err != nil {
			return err
		}
		defer store.Close()

		entities, err := knowledge.ListEntities(context.Background(), graphEntitiesTypeFilter)
		if err != nil {
			return fmt.Errorf("list entities: %w", err)
		}
		if len(entities) == 0 {
			fmt.Println("No entities found. Run `te graph seed` to populate.")
			return nil
		}

		w := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
		fmt.Fprintln(w, "TYPE\tNAME\tTICKER\tSECTOR\tCOUNTRY")
		fmt.Fprintln(w, "----\t----\t------\t------\t-------")
		for _, e := range entities {
			fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\n",
				e.EntityType, e.Name, e.Ticker, e.Sector, e.Country)
		}
		w.Flush()
		fmt.Printf("\n%d entities total.\n", len(entities))
		return nil
	},
}

func init() {
	graphEntitiesCmd.Flags().StringVarP(&graphEntitiesTypeFilter, "type", "t", "",
		"Filter by entity type (company|sector|person|country|commodity|index)")
}

// ── te graph relationships <ticker> ───────────────────────────────────────────

var graphRelationshipsCmd = &cobra.Command{
	Use:   "relationships <ticker>",
	Short: "Show 1-hop relationships for a ticker",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		ticker := strings.ToUpper(args[0])
		if err := connectDB(); err != nil {
			return err
		}
		defer store.Close()

		entity, err := knowledge.EntityByTicker(context.Background(), ticker)
		if err != nil {
			return fmt.Errorf("lookup entity: %w", err)
		}
		if entity == nil {
			fmt.Printf("No entity found for ticker %q. Run `te graph seed` or add it manually.\n", ticker)
			return nil
		}

		fmt.Printf("Entity: %s (%s | %s | %s)\n", entity.Name, entity.Ticker, entity.Sector, entity.Country)
		if entity.Description != "" {
			fmt.Printf("        %s\n", entity.Description)
		}

		rels, err := knowledge.RelatedEntities(context.Background(), ticker)
		if err != nil {
			return fmt.Errorf("get relationships: %w", err)
		}
		if len(rels) == 0 {
			fmt.Println("\nNo relationships found.")
			return nil
		}

		fmt.Printf("\n%d relationship(s):\n\n", len(rels))
		w := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
		fmt.Fprintln(w, "DIRECTION\tTYPE\tRELATED ENTITY\tTICKER\tSTRENGTH\tNOTES")
		fmt.Fprintln(w, "---------\t----\t--------------\t------\t--------\t-----")
		for _, r := range rels {
			dir := "→"
			if r.Direction == "inbound" {
				dir = "←"
			}
			auto := ""
			if r.AutoGenerated {
				auto = "[auto]"
			}
			desc := r.Description
			if len(desc) > 60 {
				desc = desc[:57] + "…"
			}
			fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%.2f\t%s %s\n",
				dir, r.RelationshipType, r.RelatedEntity.Name, r.RelatedEntity.Ticker,
				r.Strength, auto, desc)
		}
		w.Flush()
		return nil
	},
}

// ── te graph review ───────────────────────────────────────────────────────────

var graphReviewCmd = &cobra.Command{
	Use:   "review",
	Short: "Review auto-generated relationships (confirm or reject)",
	Long: `Shows relationships extracted automatically from news articles and prompts
you to confirm (c) or reject (r) each one.  Confirmed relationships have their
auto_generated flag preserved but are retained.  Rejected relationships are deleted.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		if err := connectDB(); err != nil {
			return err
		}
		defer store.Close()

		pending, err := knowledge.PendingAutoRelationships(context.Background())
		if err != nil {
			return fmt.Errorf("get pending relationships: %w", err)
		}
		if len(pending) == 0 {
			fmt.Println("No auto-generated relationships pending review.")
			return nil
		}

		fmt.Printf("%d auto-generated relationship(s) to review.\n\n", len(pending))
		scanner := bufio.NewScanner(os.Stdin)
		confirmed, rejected := 0, 0

		for i, r := range pending {
			conf := ""
			if r.Confidence != nil {
				conf = fmt.Sprintf("%.0f%%", *r.Confidence*100)
			}
			fmt.Printf("[%d/%d] %s  --%s-->  %s  (confidence: %s)\n",
				i+1, len(pending),
				r.RelatedEntity.Name, r.RelationshipType,
				r.RelatedEntity.Name, conf,
			)
			if r.Description != "" {
				fmt.Printf("       %s\n", r.Description)
			}
			fmt.Print("  [c]onfirm / [r]eject / [s]kip: ")

			if !scanner.Scan() {
				break
			}
			switch strings.ToLower(strings.TrimSpace(scanner.Text())) {
			case "c", "confirm":
				confirmed++
				fmt.Println("  ✓ Confirmed.")
			case "r", "reject":
				if err := knowledge.DeleteRelationship(context.Background(), r.ID); err != nil {
					logger.Warn("delete relationship failed", "id", r.ID, "err", err.Error())
					fmt.Printf("  ✗ Error deleting: %v\n", err)
				} else {
					rejected++
					fmt.Println("  ✗ Rejected and deleted.")
				}
			default:
				fmt.Println("  → Skipped.")
			}
			fmt.Println()
		}

		fmt.Printf("Review complete: %d confirmed, %d rejected.\n", confirmed, rejected)
		return nil
	},
}

// ── helpers ───────────────────────────────────────────────────────────────────

// connectDB initialises the store connection using the loaded config.
func connectDB() error {
	if err := store.Connect(context.Background()); err != nil {
		return fmt.Errorf("database connection failed: %w", err)
	}
	return nil
}
